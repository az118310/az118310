from guard import check
import os

check(os.path.abspath(__file__))


product = "法式复古碎花连衣裙"

# ================================================================
# 题目 1 · 长度和索引
# ================================================================
#
# 【先猜】下面输出什么？
#
print(f"长度：{len(product)}")
print(f"第一个字：{product[0]}")
print(f"第二个字：{product[1]}")

# 题 2-1：打印倒数第二个字（答案是"衣"）
# 提示：负索引，-1 是最后一个，-2 就是倒数第二个
index = -2
print(f"倒数第二个字：{product[index]}")


# ================================================================
# 题目 2 · 切片
# ================================================================
#
# 【先猜】下面输出什么？
#
print(f"切片[0:2]：{product[0:2]}")     # 前 2 个字
print(f"切片[2:]：{product[2:]}")       # 从第 2 个字到结尾
print(f"切片[:3]：{product[:3]}")       # 从开头到第 3 个字（不含 3）

# 切片规则：左闭右开 —— 包含左边，不包含右边
# product[0:2] 就是第 0 个和第 1 个

# 题 2-2：打印"复古碎花"这 4 个字
# 提示："法式复古碎花连衣裙"里，"复古"从第 2 个字开始，"碎花"到第 5 个字结束
start = 2
end = 6
print(f"切片：{product[start:end]}")


# ================================================================
# 题目 3 · 包含判断
# ================================================================
#
# 【先猜】下面两个输出什么？
#
print(f"包含'连衣裙'：{'连衣裙' in product}")
print(f"包含'衬衫'：{'衬衫' in product}")

# 题 2-3：判断商品是否包含"碎花"，打印 True/False
word = "碎花"
print(f"包含'碎花'：{word in product}")


# ================================================================
# 题目 4 · 替换
# ================================================================
#
# 【先猜】下面输出什么？
#
print(product.replace("复古", "港风"))

# 题 2-4：把"碎花"替换成"印花"，打印结果
# 提示：方法的第一个参数是要找的，第二个是要换成的
result = "碎花","港风"
print(f"替换后：{result}")


# ================================================================
# 题目 5 · 分割
# ================================================================
#
# split 把一个长字符串拆成列表
#
# 【先猜】下面输出什么？len 是多少？
#
tags = "连衣裙,夏季,新品,包邮"
parts = tags.split(",")
print(f"拆分后：{parts}")
print(f"数量：{len(parts)}")

# 题 2-5：把 "尺码齐全,顺丰包邮,七天无理由" 拆开，打印列表
new_tags = "尺码齐全,顺丰包邮,七天无理由"
print(f"拆分后：{new_tags.split(",")}")


# ================================================================
# 题目 6 · 去空格
# ================================================================
#
# 【先猜】如果直接打印，带空格的是什么样？去掉空格后呢？
#
messy = "   连衣裙   "
print(f"原始：[{messy}]")     # 用 [] 包起来才能看出空格

# 题 2-6：打印去掉两端空格后的内容
clean = "sprip"
print(f"去空格后：[{clean}]")


# ================================================================
# 题目 7 · 前缀后缀判断
# ================================================================
#
# 【先猜】下面输出什么？
#
en = "lovely dress"
print(f"大写：{en.upper()}")
print(f"以'法式'开头：{product.startswith('法式')}")
print(f"以'韩式'开头：{product.startswith('韩式')}")

# 题 2-7：判断 product 是否以"碎花"结尾（注意：连衣裙结尾不是碎花，是 False）
ends = product.endswith("碎花")
print(f"以'碎花'结尾：{ends}")


# ================================================================
# 题目 8 · 找位置
# ================================================================
#
# 【先猜】下面输出什么？（找不到会返回 -1）
#
print(f"位置：{product.find('碎花')}")
print(f"位置：{product.find('不存在')}")

# 题 2-8：找"复古"在 product 里的位置（答案是 2）
pos = product.find("复古")
print(f"位置：{pos}")


# ================================================================
# 题目 9 · 综合练习：解析商品信息
# ================================================================
#
# 真实场景：客服系统给你一条原始商品描述，你要拆出结构化字段。
#
# 题 2-9：补全下面三行（每行都要对）：
#
#     款号：A1024
#     主色：雾霾蓝
#     面料：聚酯纤维
#
raw = "款号A1024/主色雾霾蓝/面料聚酯纤维"

# 提示：先 split("/") 拆成 3 段，再对每段 split("关键词") 取 [1]
# 例如 "款号A1024".split("款号")[1] 得到 "A1024"

parts = raw.split("/")
code = parts[0].split("款号")[1]
color = parts[1].split("主色")[1]
material = parts[2].split("面料")[1]

label1 = "款号"
label2 = "主色"
label3 = "面料"

print(f"{label1}：{code}")
print(f"{label2}：{color}")
print(f"{label3}：{material}")


