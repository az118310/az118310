# ================================================================
# 题目 7 · 类型转换
# ================================================================
#
# 【先猜】这两个输出什么？
#
age_text = "28"          # 从表格里读出来的，通常都是字符串
age_num = int(age_text)  # 转成数字

print(f"字符串：{age_text}")
print(f"数字：{age_num}")

# 常见转换函数：
#   int()    -> 整数      int("189")     -> 189
#   float()  -> 小数      float("189.5")  -> 189.5
#   str()    -> 文字      str(189)       -> "189"

# 题 1-7：把 ___ 换成正确的函数，让下面输出 金额：189
amount = 189
print(f"金额：{str(amount)}")


