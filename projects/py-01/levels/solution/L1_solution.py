# ================================================================
# 题目 5 · 格式化数字
# ================================================================
#
# 【先猜】这两行分别输出什么？
#
total = 398.0

print(f"原价：{total}")
print(f"两位小数：{total:.2f}")

# 小数点后要固定几位，就在花括号里加 :.2f
# .2f 就是"保留 2 位小数"，f 是 float（浮点数）的意思

# 题 1-5：让下面这行输出 19.90（保留两位小数）
# 提示：直接写 19.9 也会输出 19.90，:.2f 是强制保留两位
print(f"单价：{19.9:.2f}")


