# 题目 3 · 数字和字符串不一样
# ================================================================
#
# 【先猜】下面两行输出什么？
#
price_text = "189.0"     # 字符串：文字
price_num = 189.0        # 数字：能算数学

print(f"字符串价格：{price_text}")
print(f"数字价格：{price_num}")

# 题 1-2：让下面这行输出 190.0
# 提示：price_text 是文字，文字不能加 1。
#       要先用 float() 或 int() 把文字变成数字，再加 1。
print(f"转换后加 1：{float(price_text) + 1}")

