# 题目 5 · continue：跳过这条，看下一条
# ================================================================
#
# 场景：批量处理工单，已处理的直接跳过
#
tickets = [
    {"id": "T1", "status": "pending", "price": 189.0},
    {"id": "T2", "status": "replied", "price": 159.0},
    {"id": "T3", "status": "pending", "price": 69.0},
    {"id": "T4", "status": "closed", "price": 259.0},
]

print("【continue 版】")
for t in tickets:
    if t["status"] != "pending":
        continue          # 不是待处理的，跳过这次循环
    print(f"  处理 {t['id']}  金额 {t['price']}")

# TODO 5-5：改成只处理金额大于 100 的待处理工单
# 提示：在 if 条件里加一个 and 条件，条件不满足就 continue
print("【金额>100 版】")
for t in tickets:
    if t["status"] != "pending":
        continue
    if t["price"] <= 100:      # TODO 5-5：确认这里的比较运算符
        continue
    print(f"  处理 {t['id']}  金额 {t['price']}")


